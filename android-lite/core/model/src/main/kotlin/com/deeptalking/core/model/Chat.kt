package com.deeptalking.core.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

@Serializable
enum class Role {
    @SerialName("system") System,
    @SerialName("user") User,
    @SerialName("assistant") Assistant,
    @SerialName("tool") Tool,
}

/**
 * A conversation message. [content] is plain text; multimodal attachments are
 * carried separately so the transport layer can build the provider payload.
 */
@Serializable
data class ChatMessage(
    val id: String = "",
    val role: Role,
    val content: String = "",
    val timestamp: String? = null,
    /** Monotonic per-conversation sequence (legacy `ensureMessageSequences`). */
    val sequence: Int = 0,
    val attachments: List<MessageAttachment> = emptyList(),
    val rejected: Boolean = false,
    /** Set on assistant turns that were generated by a proactive (unprompted) round. */
    val internalOnly: Boolean = false,
    /** True while a streamed assistant turn is still being generated. */
    val isLoading: Boolean = false,
    /** Style violations detected on this assistant turn (persisted for the review pass). */
    val styleViolations: List<String> = emptyList(),
    /** Quick-reply issues detected on this assistant turn. */
    val quickReplyIssues: List<String> = emptyList(),
    /** Legacy-only: old turns may carry static-field labels; new turns never write this. */
    val staticChanges: List<String> = emptyList(),
    /** Lorebook entry names created/updated after this assistant turn (legacy `lorebookChanges`). */
    val lorebookChanges: List<String> = emptyList(),
    /**
     * Responses `function_call` id. Set on an assistant turn that requested a tool
     * and on the matching `Role.Tool` output item (`function_call_output.call_id`).
     */
    val toolCallId: String? = null,
    /** Tool name when this assistant turn is a Responses `function_call` item. */
    val toolName: String? = null,
    /** Raw JSON arguments of the assistant `function_call`. */
    val toolArguments: String? = null,
    /**
     * JSON array of Responses `reasoning` item(s) that must be replayed before this
     * turn's `function_call` (DeepSeek thinking continuity). Null when none.
     */
    val reasoningJson: String? = null,
    /**
     * Group replies only: the per-member turns of this single assistant message
     * (`成员名：内容`), so the UI can draw one bubble per member while history and the
     * `instant` window still count the reply as one message. Empty for single
     * characters and for older messages (see [parseGroupSpeechSegments]).
     */
    val segments: List<SpeechSegment> = emptyList(),
    /**
     * 一行**给用户看**的表情结果（"表情库 +1：无语（共 13 张）" / "没发出：库里没有「委屈」"），
     * 渲染在气泡底部的小字里。它不进 [content]，所以历史回放与下一轮请求都看不到——
     * 否则角色会把自己看过的 UI 提示当成台词复述，前缀缓存也会每轮变动。
     */
    val stickerNotice: String? = null,
)

@Serializable
data class MessageAttachment(
    val kind: Kind,
    val uri: String,
    val mimeType: String? = null,
) {
    enum class Kind { Image, Sticker, File }
}
